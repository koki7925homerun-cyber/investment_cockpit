/** 見出し+本文からルールを引く。該当なしはnull。 */
export function ruleAnnotate(text) {
  for (const r of NEWS_RULES) {
    if (r.re.test(text)) {
      return {
        soWhat: r.so,
        assets: { up: [...r.up], down: [...r.down] },
        horizon: r.hz,
        impact: r.im,
        watch: r.watch,
        rule: true,
      };
    }
  }
  return null;
}

/** 記事群から今日の相場を一言でまとめる(ルールベース)。 */
export function ruleLead(items) {
  const hits = items.map((n) => ruleAnnotate(`${n.title} ${n.description || ""}`)).filter(Boolean);
  if (!hits.length) return "主要な経済ニュースを自動整理しました";
  const up = hits.filter((h) => h.impact === "up").length;
  const down = hits.filter((h) => h.impact === "down").length;
  const tone = down > up ? "警戒の色が濃い" : up > down ? "追い風が優勢な" : "強弱が入り混じる";
  const themes = [...new Set(hits.flatMap((h) => [...h.assets.up, ...h.assets.down]))].slice(0, 2);
  return `${tone}一日。${themes.length ? themes.join("と") + "の動きが焦点" : "個別材料が中心"}`;
}
